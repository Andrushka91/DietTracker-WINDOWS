using Windows.Graphics.Imaging;

namespace DietTracker.Infrastructure.FileStorage;

/// <summary>
/// Generates thumbnails with the Windows Imaging Component (through the WinRT imaging API), which
/// supports JPEG, PNG and WEBP without adding an image library to the application.
/// </summary>
public static class ThumbnailGenerator
{
    /// <summary>
    /// Creates a downscaled PNG thumbnail honouring the EXIF orientation.
    /// Returns false when the image cannot be decoded (the caller then simply has no thumbnail).
    /// </summary>
    public static async Task<bool> TryCreateAsync(string sourcePath, string targetPath, int maxSize, CancellationToken cancellationToken = default)
    {
        try
        {
            cancellationToken.ThrowIfCancellationRequested();

            using var sourceStream = File.OpenRead(sourcePath);
            using var sourceRandomAccess = sourceStream.AsRandomAccessStream();

            var decoder = await BitmapDecoder.CreateAsync(sourceRandomAccess).AsTask(cancellationToken).ConfigureAwait(false);
            if (decoder.PixelWidth == 0 || decoder.PixelHeight == 0)
            {
                return false;
            }

            // Size of the stored pixels after scaling - exactly what the BitmapTransform below asks for.
            var (scaledWidth, scaledHeight) = ScaleSize(decoder.PixelWidth, decoder.PixelHeight, maxSize);

            var transform = new BitmapTransform
            {
                ScaledWidth = scaledWidth,
                ScaledHeight = scaledHeight,
                InterpolationMode = BitmapInterpolationMode.Fant,
            };

            var pixelData = await decoder
                .GetPixelDataAsync(
                    BitmapPixelFormat.Bgra8,
                    BitmapAlphaMode.Premultiplied,
                    transform,
                    ExifOrientationMode.RespectExifOrientation,
                    ColorManagementMode.DoNotColorManage)
                .AsTask(cancellationToken)
                .ConfigureAwait(false);

            using var targetStream = File.Create(targetPath);
            using var targetRandomAccess = targetStream.AsRandomAccessStream();

            // The EXIF orientation is applied on top of the transform. For the four orientations that
            // rotate by 90° or 270° the returned buffer comes back with its width and height swapped
            // while the byte count stays identical - so declaring the unrotated size does not throw, it
            // silently makes the encoder read every row with the wrong stride and the thumbnail comes
            // out sheared, doubled and banded (the "same face repeated three times" tile).
            var exifRotates = decoder.OrientedPixelWidth != decoder.PixelWidth;
            var outputWidth = exifRotates ? scaledHeight : scaledWidth;
            var outputHeight = exifRotates ? scaledWidth : scaledHeight;

            var encoder = await BitmapEncoder.CreateAsync(BitmapEncoder.PngEncoderId, targetRandomAccess).AsTask(cancellationToken).ConfigureAwait(false);
            encoder.SetPixelData(
                BitmapPixelFormat.Bgra8,
                BitmapAlphaMode.Premultiplied,
                outputWidth,
                outputHeight,
                96,
                96,
                pixelData.DetachPixelData());

            await encoder.FlushAsync().AsTask(cancellationToken).ConfigureAwait(false);
            return true;
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            // A missing thumbnail must never block attaching a photograph.
            if (File.Exists(targetPath))
            {
                File.Delete(targetPath);
            }

            return false;
        }
    }

    /// <summary>
    /// The size an image is scaled to so that its longest edge is at most <paramref name="maxSize"/>
    /// pixels (an image is never upscaled). Always apply it to orientation-corrected dimensions, so
    /// that the value can be compared directly with an existing thumbnail.
    /// </summary>
    public static (uint Width, uint Height) ScaleSize(uint width, uint height, int maxSize)
    {
        if (width == 0 || height == 0)
        {
            return (0u, 0u);
        }

        var scale = Math.Min(1d, (double)maxSize / Math.Max(width, height));
        return (
            (uint)Math.Max(1, Math.Round(width * scale)),
            (uint)Math.Max(1, Math.Round(height * scale)));
    }

    /// <summary>
    /// True when an existing thumbnail still matches its source: the file is readable and has the size
    /// <see cref="ScaleSize"/> produces for the orientation-corrected source. Only headers are decoded,
    /// so the check is cheap enough to run over the whole photo store at start-up; thumbnails damaged
    /// by the stride bug above (their width and height are transposed) report <see langword="false"/>
    /// and are regenerated by the caller.
    /// </summary>
    public static async Task<bool> IsThumbnailValidAsync(string sourcePath, string thumbnailPath, int maxSize, CancellationToken cancellationToken = default)
    {
        try
        {
            if (!File.Exists(sourcePath) || !File.Exists(thumbnailPath))
            {
                return false;
            }

            uint orientedWidth;
            uint orientedHeight;
            using (var sourceStream = File.OpenRead(sourcePath))
            using (var sourceRandomAccess = sourceStream.AsRandomAccessStream())
            {
                var sourceDecoder = await BitmapDecoder.CreateAsync(sourceRandomAccess).AsTask(cancellationToken).ConfigureAwait(false);
                orientedWidth = sourceDecoder.OrientedPixelWidth;
                orientedHeight = sourceDecoder.OrientedPixelHeight;
            }

            var expected = ScaleSize(orientedWidth, orientedHeight, maxSize);

            using var thumbnailStream = File.OpenRead(thumbnailPath);
            using var thumbnailRandomAccess = thumbnailStream.AsRandomAccessStream();
            var thumbnailDecoder = await BitmapDecoder.CreateAsync(thumbnailRandomAccess).AsTask(cancellationToken).ConfigureAwait(false);

            // One pixel of tolerance: both sides round the scaled size.
            return Math.Abs((long)thumbnailDecoder.PixelWidth - expected.Width) <= 1
                && Math.Abs((long)thumbnailDecoder.PixelHeight - expected.Height) <= 1;
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            // An unreadable file counts as damaged: the caller regenerates it.
            return false;
        }
    }
}
