using DietTracker.App.Services;
using DietTracker.Core.Enums;
using DietTracker.Core.Interfaces;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.UI.Windowing;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using System.Runtime.InteropServices;

namespace DietTracker.App;

/// <summary>
/// Shell window: navigation between the five application areas, the synchronization status strip,
/// the notification area presence and notification deep links.
/// </summary>
public sealed partial class MainWindow : Window
{
    private readonly IServiceProvider _services;
    private readonly ILocalizationService _localization;
    private readonly ISyncEngine _syncEngine;
    private readonly ITrayIconService _trayIcon;
    private readonly IMealTrackingService _mealTracking;
    private bool _exitRequested;

    public MainWindow()
    {
        InitializeComponent();

        _services = App.Services;
        _localization = _services.GetRequiredService<ILocalizationService>();
        _syncEngine = _services.GetRequiredService<ISyncEngine>();
        _trayIcon = _services.GetRequiredService<ITrayIconService>();
        _mealTracking = _services.GetRequiredService<IMealTrackingService>();

        Title = _localization.Get("App_DisplayName");
        AppWindow.Title = Title;

        // The caption bar icon next to minimize/maximize/close - the shell draws it from the
        // window's icon, and WinUI registers its window class without one, so it must be set
        // explicitly (otherwise Windows keeps showing the generic application icon).
        ApplyWindowIcon();

        // Opens sized so all five meal cards fit, and limits resizing to the space the content uses.
        InitializeWindowSize();

        // The caption bar is drawn by the shell, not by XAML: paint it with the colour of the
        // system app theme (dark on a dark Windows, light on a light Windows) and repaint it
        // whenever the XAML theme switches, so it always matches the interface below it.
        ApplyTitleBarTheme();
        RootGrid.ActualThemeChanged += (_, _) => ApplyTitleBarTheme();

        _syncEngine.StateChanged += OnSyncStateChanged;
        _services.GetRequiredService<INotificationService>().Activated += OnNotificationActivated;

        _trayIcon.RestoreRequested += (_, _) => RestoreFromTray();
        _trayIcon.ExitRequested += (_, _) => ExitApplication();

        AppWindow.Closing += OnWindowClosing;

        Navigate("dashboard");
    }

    /// <summary>DWM attribute that lets a window paint its own caption in dark mode (Windows 10 2004+).</summary>
    private const int DwmwaUseImmersiveDarkMode = 20;

    /// <summary>The same attribute under its original number, for the older Windows 10 builds.</summary>
    private const int DwmwaUseImmersiveDarkModeLegacy = 9;

    [DllImport("dwmapi.dll")]
    private static extern int DwmSetWindowAttribute(IntPtr hwnd, int attribute, ref int value, int valueSize);

    /// <summary>
    /// Paints the window title bar in the colour of the Windows app theme: dark when Windows runs in
    /// dark mode, light when it runs in light mode. The bar is drawn by the shell (the XAML content
    /// does not extend into it), so without this call it would stay light even while the whole
    /// application renders dark. The colours come from the system itself, so the bar and the
    /// interface always follow the same setting - including live switches made while the app runs
    /// (the change event re-applies the attribute).
    /// </summary>
    private void ApplyTitleBarTheme()
    {
        try
        {
            var hwnd = WinRT.Interop.WindowNative.GetWindowHandle(this);

            // The same system setting the XAML theme follows: dark Windows gets a dark title bar,
            // light Windows a light one.
            var useDarkMode = ThemeHelper.IsDarkAppMode() ? 1 : 0;

            // Attribute 20 is unknown on the older Windows 10 builds, which only know 9.
            if (DwmSetWindowAttribute(hwnd, DwmwaUseImmersiveDarkMode, ref useDarkMode, sizeof(int)) != 0)
            {
                DwmSetWindowAttribute(hwnd, DwmwaUseImmersiveDarkModeLegacy, ref useDarkMode, sizeof(int));
            }
        }
        catch (Exception)
        {
            // The caption keeps the shell default colour - never fail the window for the title bar.
        }
    }

    /// <summary>
    /// Puts the DietTracker mark in the caption bar (next to minimize/maximize/close) and in
    /// Alt+Tab. The icon is the same <c>Assets\DietTracker.ico</c> that ships next to the
    /// executable (generated by <c>tools/Generate-StoreAssets.ps1</c>); the path has to be
    /// absolute because the window can be opened from any working directory (Start menu,
    /// tray, notification deep link). A missing file or a failing API only costs the pretty
    /// icon - the window must still open, so every failure is swallowed like in
    /// <see cref="ApplyTitleBarTheme"/>.
    /// </summary>
    private void ApplyWindowIcon()
    {
        try
        {
            var iconPath = Path.Combine(AppContext.BaseDirectory, "Assets", "DietTracker.ico");
            if (File.Exists(iconPath))
            {
                AppWindow.SetIcon(iconPath);
            }
        }
        catch (Exception)
        {
            // The caption keeps the shell default icon - never fail the window for the title bar.
        }
    }

    /// <summary>Navigates to a page by tag, keeping the navigation item selection in sync.</summary>
    public void Navigate(string tag, object? parameter = null)
    {
        var pageType = tag switch
        {
            "calendar" => typeof(Views.CalendarPage),
            "statistics" => typeof(Views.StatisticsPage),
            "templates" => typeof(Views.TemplatesPage),
            "account" => typeof(Views.AccountSyncPage),
            "settings" => typeof(Views.SettingsPage),
            "onboarding" => typeof(Views.OnboardingPage),
            _ => typeof(Views.DashboardPage),
        };

        if (ContentFrame.CurrentSourcePageType != pageType)
        {
            ContentFrame.Navigate(pageType, parameter);
        }

        foreach (var item in Navigation.MenuItems.OfType<NavigationViewItem>())
        {
            if (item.Tag is string itemTag && itemTag == tag)
            {
                Navigation.SelectedItem = item;
            }
        }
    }

    private void OnNavigationSelectionChanged(NavigationView sender, NavigationViewSelectionChangedEventArgs args)
    {
        if (args.SelectedItem is NavigationViewItem { Tag: string tag })
        {
            Navigate(tag);
        }
    }

    private void OnWindowClosing(AppWindow sender, AppWindowClosingEventArgs args)
    {
        if (_exitRequested || !MinimizeToTrayEnabled())
        {
            _trayIcon.HideAsync().GetAwaiter().GetResult();
            return;
        }

        // Closing the window keeps reminders working from the notification area; the user exits
        // explicitly through the tray menu or the Settings page.
        args.Cancel = true;
        AppWindow.Hide();
        _trayIcon.ShowAsync().GetAwaiter().GetResult();
    }

    private bool MinimizeToTrayEnabled()
    {
        try
        {
            var profiles = _services.GetRequiredService<IProfileService>();
            return profiles.GetPreferencesAsync().GetAwaiter().GetResult().MinimizeToTray;
        }
        catch (Exception)
        {
            return false;
        }
    }

    private void RestoreFromTray()
    {
        AppWindow.Show();
        Activate();
    }

    private void ExitApplication()
    {
        _exitRequested = true;
        _trayIcon.HideAsync().GetAwaiter().GetResult();
        Application.Current.Exit();
    }
}
